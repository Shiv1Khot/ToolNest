/* ToolNest i18n — English/Hindi string tables and language switching.
   Generated by /tmp/gen_i18n.py — do not hand-edit. */
(function () {
  "use strict";
  window.ToolNestStrings = {en:{}, hi:{}};
  var LS_KEY = "toolnest-lang";
  function storedLang() {
    try {
      var v = localStorage.getItem(LS_KEY);
      if (v === "en" || v === "hi") return v;
    } catch (e) {}
    return null;
  }
  function autoLang() {
    var n = (navigator.language || navigator.userLanguage || "en").toLowerCase();
    return n.indexOf("hi") === 0 ? "hi" : "en";
  }
  var lang = storedLang() || autoLang();

  function t(key, params) {
    var tab = window.ToolNestStrings[lang] || window.ToolNestStrings.en;
    var s = tab[key];
    if (s === undefined) s = window.ToolNestStrings.en[key];
    if (s === undefined) return key;
    if (params) {
      s = String(s).replace(/\{(\w+)\}/g, function (m, p) {
        return params[p] !== undefined && params[p] !== null ? params[p] : m;
      });
    }
    return s;
  }

  function setToggleUI() {
    var btns = document.querySelectorAll("[data-lang-toggle]");
    btns.forEach(function (btn) {
      btn.querySelectorAll("[data-lang-opt]").forEach(function (sp) {
        sp.classList.toggle("active", sp.getAttribute("data-lang-opt") === lang);
      });
    });
  }

  function apply() {
    document.documentElement.setAttribute("lang", lang);
    setToggleUI();
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    document.querySelectorAll("[data-i18n-content]").forEach(function (el) {
      el.setAttribute("content", t(el.getAttribute("data-i18n-content")));
    });
    if (window.ToolNest) {
      if (ToolNest.refreshDropzones) { try { ToolNest.refreshDropzones(); } catch (e) {} }
      if (ToolNest.refreshSearch) { try { ToolNest.refreshSearch(); } catch (e) {} }
    }
  }

  function setLang(l) {
    if (l !== "en" && l !== "hi") return;
    lang = l;
    try { localStorage.setItem(LS_KEY, l); } catch (e) {}
    apply();
  }

  document.addEventListener("click", function (e) {
    var el = e.target && e.target.closest ? e.target.closest("[data-lang-toggle]") : null;
    if (el) setLang(lang === "hi" ? "en" : "hi");
  });

  document.documentElement.setAttribute("lang", lang);
  window.I18N = {
    t: t,
    getLang: function () { return lang; },
    setLang: setLang,
    apply: apply
  };
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", apply);
  } else {
    apply();
  }
})();
